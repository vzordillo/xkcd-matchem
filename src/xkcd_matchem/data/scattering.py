def atomic_form_factor(
    symbol: str,
    s_inv_angstrom: float | np.ndarray,
) -> np.ndarray:
    """Evaluates the neutral X-ray atomic scattering factor ``f(s)``.

    Neutral hydrogen (Z=1) is absent from neutral-atom Table II in LA-3816
    and uses the exact analytical spherical 1s form factor
    ``(1 + (2 * pi * a_0 * s)^2)^(-2)``. Elements Z=2..103 use the verified
    Cromer-Mann (1967) LA-3816 Table II 4-Gaussian analytical fit. Elements
    with Z > 103 fall back to Z-scaled Lr screening.

    Args:
      symbol: Chemical element symbol.
      s_inv_angstrom: Momentum transfer ``sin(theta) / lambda`` in A^-1.

    Returns:
      Array (or scalar 0-d array) of real form factor values.
    """
    rec = elements.get_element(symbol)
    s_arr = np.asarray(s_inv_angstrom, dtype=np.float64)
    s2 = np.square(s_arr)
    if rec.atomic_number == 1:
        h_prefactor = (
            2.0 * math.pi * elements.CODATA2022.bohr_to_angstrom
        ) ** 2
        return 1.0 / np.square(1.0 + h_prefactor * s2)
    coeffs = CROMER_MANN_TABLE.get(rec.symbol)
    scale = 1.0
    if coeffs is None:
        coeffs = CROMER_MANN_TABLE["Lr"]
        scale = float(rec.atomic_number) / 103.0
    a_vec = np.asarray(coeffs.a, dtype=np.float64)
    b_vec = np.asarray(coeffs.b, dtype=np.float64)
    gauss_sum = np.sum(a_vec * np.exp(-b_vec * s2[..., None]), axis=-1)
    return np.asarray((coeffs.c + gauss_sum) * scale, dtype=np.float64)
