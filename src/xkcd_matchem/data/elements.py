ELEMENTS_BY_SYMBOL: dict[str, ElementRecord] = {
    record.symbol: record for record in ELEMENTS_BY_Z.values()
}

_ELEMENTS_BY_SYMBOL_LOWER: dict[str, ElementRecord] = {
    record.symbol.lower(): record for record in ELEMENTS_BY_Z.values()
}


def get_element(identifier: int | str) -> ElementRecord:
    """Looks up an ``ElementRecord`` by atomic number or symbol.

    Args:
      identifier: Atomic number ``1..118`` or chemical symbol (any case).

    Returns:
      Matching ``ElementRecord``.

    Raises:
      StructureError: If the atomic number or symbol is unknown.
    """
    if isinstance(identifier, int):
        if identifier not in ELEMENTS_BY_Z:
            raise _exceptions.StructureError(
                f"Unknown atomic number: {identifier}"
            )
        return ELEMENTS_BY_Z[identifier]
    key = str(identifier).strip().lower()
    if key not in _ELEMENTS_BY_SYMBOL_LOWER:
        raise _exceptions.StructureError(
            f"Unknown element symbol: {identifier!r}"
        )
    return _ELEMENTS_BY_SYMBOL_LOWER[key]


def get_atomic_mass(identifier: int | str) -> float:
    """Returns the IUPAC/CIAAW atomic mass (Da) for an element."""
    return get_element(identifier).atomic_mass


def get_covalent_radius(identifier: int | str) -> float:
    """Returns the BODR covalent radius (Angstrom) for an element."""
    return get_element(identifier).covalent_radius


def get_vdw_radius(identifier: int | str) -> float:
    """Returns the van der Waals radius (Angstrom) for an element."""
    return get_element(identifier).vdw_radius


def get_jmol_color(identifier: int | str) -> str:
    """Returns the Jmol CPK hex color string for an element."""
    return get_element(identifier).jmol_color
